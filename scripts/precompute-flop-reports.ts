import { writeFileSync } from "fs";
import { FLOP_GROUPS, computeAllReports, sampleFlops } from "../src/utils/flopReports";

const pool = sampleFlops(14);
const table: Record<string, unknown> = {};
for (const g of FLOP_GROUPS) {
  const t = Date.now();
  table[g.id] = { flop: pool[g.id][0], reports: computeAllReports(g.id, pool) };
  console.log(g.id, Date.now() - t, "ms");
}

const src = `/* Auto-generated by scripts/precompute-flop-reports.ts. Do not edit by hand. */
export const FLOP_REPORT_TABLE = ${JSON.stringify(table, null, 2)};
`;
writeFileSync("src/data/flopReportTable.ts", src);
console.log("wrote src/data/flopReportTable.ts");
